import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row
from flask import current_app, g

SCHEMA = """
CREATE TABLE IF NOT EXISTS workspace_settings (
    id INTEGER PRIMARY KEY CHECK(id = 1),
    freelancer_display_name TEXT NOT NULL CHECK(length(freelancer_display_name) <= 120),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS payment_requests (
    id INTEGER PRIMARY KEY,
    public_token TEXT NOT NULL UNIQUE,
    client_name TEXT NOT NULL,
    service_description TEXT NOT NULL,
    amount_cents INTEGER NOT NULL CHECK(amount_cents > 0),
    currency TEXT NOT NULL DEFAULT 'USD' CHECK(currency = 'USD'),
    due_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'unpaid' CHECK(status IN ('unpaid','paid')),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    paid_at TEXT,
    archived_at TEXT,
    capture_id TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS payment_attempts (
    id TEXT PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES payment_requests(id),
    order_id TEXT UNIQUE,
    capture_id TEXT UNIQUE,
    create_key TEXT NOT NULL UNIQUE,
    capture_key TEXT NOT NULL UNIQUE,
    state TEXT NOT NULL,
    diagnostic TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    capture_started_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_attempt
ON payment_attempts(request_id) WHERE state NOT IN ('failed', 'completed');
CREATE TABLE IF NOT EXISTS payment_events (
    id INTEGER PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES payment_requests(id),
    attempt_id TEXT REFERENCES payment_attempts(id),
    kind TEXT NOT NULL CHECK(kind IN ('request_created','order_created','payment_confirmed','attempt_cancelled','attempt_failed','order_unavailable')),
    occurred_at TEXT NOT NULL,
    event_key TEXT NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS payment_events_request ON payment_events(request_id, occurred_at, id);
"""

# Keep integer cents and ISO text dates/timestamps identical across backends.
# PostgreSQL needs explicit identity columns (SQLite generates INTEGER PKs).
POSTGRES_SCHEMA = SCHEMA.replace(
    "id INTEGER PRIMARY KEY,", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
).replace("request_id INTEGER", "request_id BIGINT")

# One workspace-wide, transaction-scoped lock, shared by ALL mutation paths.
# Unlike session locks, this is safe with PgBouncer transaction pooling.
WORKSPACE_LOCK = 761814230651


class DatabaseConnectionError(RuntimeError):
    """Safe startup diagnostic: never include a DSN or driver exception body."""


class PostgresDatabase:
    """Small adapter for this application's static qmark SQL, not arbitrary SQL.

    Values remain separate bound parameters; no interpolation of user data.
    Application SQL contains no literal question marks or percent operators.
    """

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, parameters=None):
        return self.connection.execute(sql.replace("?", "%s"), parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def attempt_order_column():
    # UUIDs and second-resolution timestamps cannot reliably order tied inserts.
    # Keep SQLite's existing insertion order; PostgreSQL persists its equivalent.
    return "attempt_sequence" if current_app.config.get("DATABASE_URL") else "rowid"


def get_db():
    if "db" not in g:
        url = current_app.config.get("DATABASE_URL", "")
        if url:
            try:
                if not url.startswith(("postgresql://", "postgres://")):
                    raise ValueError()
                options = conninfo_to_dict(url)
                # Never permit an accidentally unencrypted remote connection.
                if options.get("sslmode", "require") not in ("require", "verify-ca", "verify-full"):
                    raise ValueError()
                connection = psycopg.connect(
                    url, autocommit=True, row_factory=dict_row, prepare_threshold=None,
                    connect_timeout=15, sslmode=options.get("sslmode", "require"),
                )
            except (psycopg.Error, ValueError):
                raise DatabaseConnectionError("PostgreSQL connection failed. Check the server-only DATABASE_URL and network; credentials are not logged.") from None
            g.db = PostgresDatabase(connection)
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"], timeout=35, isolation_level=None)
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
            g.db.execute("PRAGMA busy_timeout = 35000")
    return g.db


@contextmanager
def transaction():
    db = get_db()
    try:
        if isinstance(db, PostgresDatabase):
            db.execute("BEGIN ISOLATION LEVEL READ COMMITTED")
            db.execute("SET LOCAL lock_timeout = '35s'")
            db.execute("SET LOCAL statement_timeout = '60s'")
            # Acquire BEFORE reading state. READ COMMITTED gives waiting writers
            # a fresh snapshot after the previous writer commits.
            db.execute("SELECT pg_advisory_xact_lock(?)", (WORKSPACE_LOCK,))
        else:
            db.execute("BEGIN IMMEDIATE")
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise


def init_db():
    postgres = bool(current_app.config.get("DATABASE_URL"))
    if not postgres:
        Path(current_app.config["DATABASE"]).parent.mkdir(parents=True, exist_ok=True)
        get_db().execute("PRAGMA journal_mode = WAL")
    # DDL and migration ledger are atomic, additive and serialized with payments.
    # No executescript: SQLite executescript would implicitly commit our lock.
    with transaction() as db:
        for statement in (POSTGRES_SCHEMA if postgres else SCHEMA).split(";"):
            if statement.strip():
                db.execute(statement)
        db.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)")
        if postgres:
            db.execute("ALTER TABLE payment_requests ADD COLUMN IF NOT EXISTS archived_at TEXT")
        else:
            columns = {row["name"] for row in db.execute("PRAGMA table_info(payment_requests)")}
            if "archived_at" not in columns:
                db.execute("ALTER TABLE payment_requests ADD COLUMN archived_at TEXT")
        db.execute("CREATE INDEX IF NOT EXISTS requests_archive ON payment_requests(archived_at, created_at, id)")
        db.execute("INSERT INTO schema_migrations (version, applied_at) VALUES (1, ?) ON CONFLICT(version) DO NOTHING", (now(),))
        if postgres:
            # Migration 2: no request/payment values are updated. For the initial
            # Neon setup this table has no attempts. Legacy imports must explicitly
            # preserve SQLite rowid as attempt_sequence, then advance its sequence.
            sequence_exists = db.execute(
                "SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='payment_attempts' AND column_name='attempt_sequence'"
            ).fetchone()
            if not sequence_exists and db.execute("SELECT COUNT(*) AS count FROM payment_attempts").fetchone()["count"]:
                raise DatabaseConnectionError("Payment attempts need a reviewed insertion-order backfill before migration 2. No payment data was reset or rewritten.")
            db.execute("ALTER TABLE payment_attempts ADD COLUMN IF NOT EXISTS attempt_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY")
            db.execute("CREATE UNIQUE INDEX IF NOT EXISTS payment_attempts_sequence ON payment_attempts(attempt_sequence)")
        db.execute("INSERT INTO schema_migrations (version, applied_at) VALUES (2, ?) ON CONFLICT(version) DO NOTHING", (now(),))
        # Migration 3: authentication/rate-limit metadata, never payment history.
        db.execute("""CREATE TABLE IF NOT EXISTS management_sessions (
            token_hash TEXT PRIMARY KEY, credential_version TEXT NOT NULL,
            expires_at BIGINT NOT NULL, created_at TEXT NOT NULL
        )""")
        db.execute("CREATE INDEX IF NOT EXISTS management_sessions_expiry ON management_sessions(expires_at)")
        db.execute("""CREATE TABLE IF NOT EXISTS request_limits (
            bucket TEXT PRIMARY KEY, starts_at BIGINT NOT NULL,
            attempts INTEGER NOT NULL CHECK(attempts >= 0)
        )""")
        db.execute("INSERT INTO schema_migrations (version, applied_at) VALUES (3, ?) ON CONFLICT(version) DO NOTHING", (now(),))


def close_db(_error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()

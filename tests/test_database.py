def test_postgres_connection_options_binding_and_close(postgres_app):
    app, connection, connect = postgres_app
    with app.app_context():
        db = get_db()
        assert db is get_db()
        connect.assert_called_once()
        options = connect.call_args.kwargs
        assert options["autocommit"] is True
        assert options["prepare_threshold"] is None
        assert options["sslmode"] == "require"
        assert options["connect_timeout"] == 15
        value = "Fictional O'Demo ? 100%"
        db.execute("SELECT * FROM payment_requests WHERE client_name=?", (value,))
        connection.execute.assert_called_with("SELECT * FROM payment_requests WHERE client_name=%s", (value,))
    connection.close.assert_called_once()


def test_postgres_transaction_lock_precedes_reads_and_commits(postgres_app):
    app, connection, _ = postgres_app
    with app.app_context():
        with transaction() as db:
            assert isinstance(db, PostgresDatabase)
            db.execute("SELECT * FROM payment_requests")
    commands = [call.args for call in connection.execute.call_args_list]
    assert commands == [
        ("BEGIN ISOLATION LEVEL READ COMMITTED", None),
        ("SET LOCAL lock_timeout = '35s'", None),
        ("SET LOCAL statement_timeout = '60s'", None),
        ("SELECT pg_advisory_xact_lock(%s)", (WORKSPACE_LOCK,)),
        ("SELECT * FROM payment_requests", None),
    ]
    connection.commit.assert_called_once()
    connection.rollback.assert_not_called()


@pytest.mark.parametrize("fail_on_lock", [False, True])
def test_postgres_rolls_back_body_and_lock_failures(postgres_app, fail_on_lock):
    app, connection, _ = postgres_app
    if fail_on_lock:
        def execute(sql, _parameters):
            if "pg_advisory_xact_lock" in sql:
                raise psycopg.OperationalError("fictional lock timeout")
        connection.execute.side_effect = execute
    with app.app_context(), pytest.raises((ValueError, psycopg.OperationalError)):
        with transaction():
            raise ValueError("abort")
    connection.rollback.assert_called_once()
    connection.commit.assert_not_called()


def test_postgres_schema_is_additive_and_transactional(postgres_app):
    app, connection, _ = postgres_app
    with app.app_context():
        init_db()
    commands = [call.args[0] for call in connection.execute.call_args_list]
    assert commands[0].startswith("BEGIN")
    assert "ALTER TABLE payment_requests ADD COLUMN IF NOT EXISTS archived_at TEXT" in commands
    assert not any("DROP " in sql or "DELETE " in sql or "PRAGMA" in sql for sql in commands)
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in POSTGRES_SCHEMA
    assert "request_id BIGINT NOT NULL REFERENCES payment_requests(id)" in POSTGRES_SCHEMA
    assert "amount_cents INTEGER NOT NULL" in POSTGRES_SCHEMA
    assert "one_active_attempt" in POSTGRES_SCHEMA
    assert "capture_id TEXT UNIQUE" in POSTGRES_SCHEMA
    connection.commit.assert_called_once()


def test_connection_failure_never_exposes_credentials(postgres_app):
    app, _, connect = postgres_app
    connect.side_effect = psycopg.OperationalError(app.config["DATABASE_URL"])
    with app.app_context(), pytest.raises(DatabaseConnectionError) as caught:
        get_db()
    assert "never-a-real-secret" not in str(caught.value)
    assert caught.value.__suppress_context__



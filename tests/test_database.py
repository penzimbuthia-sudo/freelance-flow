def test_migrations_repeat_without_changing_payment_data(app, client, saved, approved, named):
    with app.app_context():
        tables = ("payment_requests", "payment_attempts", "payment_events", "workspace_settings", "schema_migrations")
        before = {table: [tuple(row) for row in get_db().execute(f"SELECT * FROM {table}")] for table in tables}
        init_db()
        init_db()
        after = {table: [tuple(row) for row in get_db().execute(f"SELECT * FROM {table}")] for table in tables}
        assert before == after
    reopened = create_app(dict(app.config)).test_client()
    assert reopened.get("/api/settings").json["settings"]["freelancer_display_name"] == named
    assert reopened.get(f'/api/requests/{saved["id"]}').json["request"]["amount_cents"] == 5010



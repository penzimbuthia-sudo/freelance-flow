import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function create(request, name) {
  const response = await request.post('/api/requests', { data: { client_name: name, service_description: 'Fictional archive regression service', amount: '7.89', due_date: '2030-11-12' } })
  expect(response.status()).toBe(201)
  return (await response.json()).request
}

for (const width of [375, 1440]) {
  test(`archive/restore is reversible and old unpaid links are unavailable at ${width}px`, async ({ page, context, request }, testInfo) => {
    await page.setViewportSize({ width, height: 950 })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
    await request.post('/__test__/services', { data: { enabled: false } })
    await request.put('/api/settings', { data: { freelancer_display_name: 'Archive Fixture Sender' } })
    const item = await create(request, `Archive Fixture ${width}`)
    const before = await (await request.get(`/api/requests/${item.id}`)).json()
    const totalsBefore = await (await request.get('/api/dashboard')).json()
    const publicPage = await context.newPage()
    await publicPage.goto(new URL(item.payment_url).pathname)
    await expect(publicPage.locator('.checkout-amount')).toContainText('$7.89')
    await page.goto(`/requests/${item.id}`)
    const archive = page.getByRole('button', { name: 'Archive request', exact: true })
    const dialog = page.getByRole('dialog', { name: 'Archive this request?' })
    const keep = dialog.getByRole('button', { name: 'Keep request' })
    await archive.click()
    await expect(keep).toBeFocused()
    await expect(dialog).toHaveAccessibleDescription(/without deleting its payment history/)
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Archive request', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(keep).toBeFocused()
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await page.screenshot({ path: testInfo.outputPath(`archive-dialog-${width}.png`) })
    await page.keyboard.press('Escape')
    await expect(archive).toBeFocused()
    expect((await (await request.get(`/api/requests/${item.id}`)).json()).request.archived).toBe(false)

    // Preserve an edited message and sender setting while hiding the request.
    const draft = page.getByLabel('Review and edit your message')
    await draft.fill('Archive must preserve this unsent fixture draft.')
    await archive.click()
    let release
    const gate = new Promise((resolve) => { release = resolve })
    const delayed = async (route) => { await gate; await route.continue() }
    await page.route(`**/api/requests/${item.id}/archive`, delayed)
    await dialog.getByRole('button', { name: 'Archive request', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Archiving…' })).toBeDisabled()
    await expect(keep).toBeDisabled()
    release()
    await expect(dialog).toHaveCount(0)
    await page.unroute(`**/api/requests/${item.id}/archive`, delayed)
    await expect(page.getByRole('button', { name: 'Restore request', exact: true })).toBeFocused()
    await expect(page.getByRole('status').filter({ hasText: 'Archived request.' })).toBeVisible()
    await expect(draft).toHaveValue('Archive must preserve this unsent fixture draft.')
    await expect(page.getByRole('button', { name: 'Generate payment message' })).toBeDisabled()
    await expect(page.getByRole('note', { name: 'Payment facts' })).toContainText('restore the request before sharing')
    await publicPage.bringToFront()
    await publicPage.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(publicPage.getByRole('alert')).toContainText('This payment request is no longer available.')
    await expect(publicPage.locator('.checkout-card')).toHaveCount(0)
    await publicPage.close()
    const totals = await (await request.get('/api/dashboard')).json()
    expect(totals.request_count).toBe(totalsBefore.request_count - 1)
    expect(totals.outstanding_cents).toBe(totalsBefore.outstanding_cents - 789)
    expect(totals.recent_requests.some((row) => row.id === item.id)).toBe(false)
    const after = await (await request.get(`/api/requests/${item.id}`)).json()
    expect(after.activity).toEqual(before.activity)
    expect(after.request.status).toBe(before.request.status)

    await page.locator('.ai-actions').getByRole('button', { name: 'Clear draft', exact: true }).click()
    await page.getByRole('dialog', { name: 'Clear this draft?' }).getByRole('button', { name: 'Clear draft', exact: true }).click()
    await page.getByRole('navigation').getByRole('link', { name: 'Payment requests', exact: true }).click()
    await expect(page.getByRole('link', { name: item.client_name, exact: true })).toHaveCount(0)
    await page.getByLabel('Status', { exact: true }).selectOption('archived')
    await page.getByRole('link', { name: item.client_name, exact: true }).click()
    await expect(page.getByRole('button', { name: 'Restore request' })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Restore request' }).click()
    await expect(page.getByRole('button', { name: 'Archive request', exact: true })).toBeVisible()
    expect(await (await request.get(`/api/requests/${item.id}`)).json()).toEqual(before)
    expect(await (await request.get('/api/dashboard')).json()).toEqual(totalsBefore)
    await page.getByRole('navigation').getByRole('link', { name: 'Dashboard', exact: true }).click()
    await expect(page.getByText('Totals exclude archived requests.', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: item.client_name, exact: true })).toBeVisible()
    expect(errors).toEqual([])
  })
}

test('unresolved payment blocks archive with an inline error; paid confirmation survives archive', async ({ page, request }, testInfo) => {
  await request.post('/__test__/services', { data: { enabled: true } })
  try {
    const item = await create(request, 'Archive Payment Safeguard Fixture')
    const publicPath = new URL(item.payment_url).pathname
    const api = `/api/public/requests/${publicPath.split('/').pop()}`
    const { order_id: orderId } = await (await request.post(api + '/orders')).json()
    await request.post('/__test__/approve', { data: { order_id: orderId } })
    await page.goto(`/requests/${item.id}`)
    await page.getByRole('button', { name: 'Archive request', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Archive this request?' })
    await dialog.getByRole('button', { name: 'Archive request', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('Finish or reconcile the payment attempt')
    await expect(dialog.getByRole('button', { name: 'Keep request' })).toBeFocused()
    expect((await (await request.get(`/api/requests/${item.id}`)).json()).request.archived).toBe(false)
    await dialog.getByRole('button', { name: 'Keep request' }).click()
    expect((await request.post(api + '/capture', { data: { order_id: orderId } })).status()).toBe(200)
    const confirmationBefore = (await (await request.get(api)).json()).request.confirmation
    await page.getByRole('button', { name: 'Refresh status' }).click()
    await expect(page.getByRole('heading', { name: 'Payment confirmed', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Archive request', exact: true }).click()
    await dialog.getByRole('button', { name: 'Archive request', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Restore request' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Payment confirmed', exact: true })).toBeVisible()
    await page.emulateMedia({ media: 'print' })
    await expect(page.locator('.payment-confirmation')).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Archived request.' })).toBeHidden()
    await expect(page.getByRole('button', { name: 'Print confirmation' })).toBeHidden()
    await page.pdf({ path: testInfo.outputPath('archived-paid-confirmation.pdf'), format: 'A4', displayHeaderFooter: false })
    await page.emulateMedia({ media: 'screen' })
    await page.goto(publicPath)
    await expect(page.getByRole('heading', { name: 'Payment confirmed', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Print confirmation' })).toBeVisible()
    expect((await (await request.get(api)).json()).request.confirmation).toEqual(confirmationBefore)
  } finally {
    await request.post('/__test__/services', { data: { enabled: false } })
  }
})

test('nested leave-draft and archive dialogs release scroll locks when leaving', async ({ page, request }) => {
  const item = await create(request, 'Nested Archive Dialog Fixture')
  await page.goto('/')
  await page.getByRole('link', { name: item.client_name, exact: true }).click()
  await page.getByLabel('Review and edit your message').fill('Unsent fixture edit.')
  await page.getByRole('button', { name: 'Archive request', exact: true }).click()
  await page.evaluate(() => history.back())
  const leave = page.getByRole('dialog', { name: 'Leave this draft?' })
  await expect(leave).toBeVisible()
  await leave.getByRole('button', { name: 'Leave page' }).click()
  await expect(page.getByRole('heading', { name: 'Your money, in view.' })).toBeVisible()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  expect((await (await request.get(`/api/requests/${item.id}`)).json()).request.archived).toBe(false)
})
